#!/usr/bin/env bash
#
# Configures /etc/4xxx_dev[0-7].conf for IAXL KV compression and restarts QAT.
# Run as root on the host; each changed file is backed up to <file>.bak.<timestamp>.
#
# - ServicesEnabled = dc: with a second service (e.g. asym;dc) a QAT 2.0 device splits its
#   8 engines 4|4, leaving compression only half. Crypto instances and Kpt* keys are removed.
# - [SSL] NumProcesses = 4, NumberDcInstances = 8: up to 4 processes (e.g. TP ranks) share
#   QAT, each with 8 instances per device. dc-only allows at most 64 instances per device.
# - Dc CoreAffinity: CPUs of the device's own NUMA node, different CPUs for each device.
# - SVMEnabled/ATEnabled: set only when the kernel runs with iommu=on or iommu=pt.

set -euo pipefail

if [[ "${EUID}" -ne 0 ]]; then
    echo "ERROR: this script must be run as root (use sudo)." >&2
    exit 1
fi

CONFS=()
for f in /etc/4xxx_dev[0-7].conf; do
    [[ -f "$f" ]] && CONFS+=("$f")
done

if [[ ${#CONFS[@]} -eq 0 ]]; then
    echo "ERROR: no /etc/4xxx_dev[0-7].conf found." >&2
    echo "       Run this on the host, not inside a container, and make sure QAT is installed." >&2
    exit 1
fi

IOMMU=0
if grep -qE "iommu=(on|pt)" /proc/cmdline; then
    IOMMU=1
    echo "IOMMU enabled: adding SVMEnabled/ATEnabled to [GENERAL]"
else
    echo "IOMMU disabled: removing SVMEnabled/ATEnabled from [GENERAL]"
fi

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

SSL_NUM_PROCESSES=4
SSL_NUM_DC_INSTANCES=8
echo "Setting [SSL] NumProcesses = $SSL_NUM_PROCESSES, NumberDcInstances = $SSL_NUM_DC_INSTANCES"
echo "Setting ServicesEnabled = dc (sym/asym crypto and their instances are removed)"

# CPUs of NUMA node $1 (all online CPUs when the node is unknown), one per line.
node_cpus() {
    local range list=/sys/devices/system/cpu/online
    (($1 >= 0)) && list=/sys/devices/system/node/node$1/cpulist
    for range in $(tr ',' ' ' <"$list"); do
        seq "${range%-*}" "${range#*-}"
    done
}

# /etc/4xxx_devN.conf configures the 4xxx device whose inst_id is N.
declare -A BSF_OF NODE_RANK AFFINITY
while read -r inst bsf; do
    BSF_OF[$inst]=$bsf
done < <(adf_ctl status | sed -nE 's/.*type: 4xxx, +inst_id: ([0-9]+),.* bsf: ([0-9a-f:.]+),.*/\1 \2/p')

for CONF in "${CONFS[@]}"; do
    inst=${CONF##*_dev}
    inst=${inst%.conf}
    bsf=${BSF_OF[$inst]:-}
    if [[ -z "$bsf" ]]; then
        echo "ERROR: 'adf_ctl status' lists no 4xxx device with inst_id $inst." >&2
        exit 1
    fi
    node=$(<"/sys/bus/pci/devices/$bsf/numa_node")
    mapfile -t cpus < <(node_cpus "$node")
    # Devices sharing a node take consecutive CPUs of it.
    rank=${NODE_RANK[$node]:-0}
    NODE_RANK[$node]=$((rank + 1))
    for ((i = 0; i < SSL_NUM_DC_INSTANCES; i++)); do
        cpu=${cpus[(rank * SSL_NUM_DC_INSTANCES + i) % ${#cpus[@]}]}
        AFFINITY[$CONF]+="${AFFINITY[$CONF]:+,}$cpu"
    done
    echo "  $CONF: $bsf on NUMA node $node, Dc CoreAffinity = ${AFFINITY[$CONF]}"
done

for CONF in "${CONFS[@]}"; do
    awk -v iommu="$IOMMU" -v procs="$SSL_NUM_PROCESSES" -v ndc="$SSL_NUM_DC_INSTANCES" \
        -v affinity="${AFFINITY[$CONF]}" '
        function emit_dc(    i, cores) {
            split(affinity, cores, ",")
            for (i = 0; i < ndc; i++) {
                print ""
                print "# Data Compression - User instance #" i
                print "Dc" i "Name = \"Dc" i "\""
                print "Dc" i "IsPolled = 1"
                print "# List of core affinities"
                print "Dc" i "CoreAffinity = " cores[i + 1]
            }
        }
        /^[[:space:]]*\[/ {
            if (section == "SSL")
                emit_dc()
            section = $0
            gsub(/[][[:space:]]/, "", section)
        }
        /^[[:space:]]*(SVMEnabled|ATEnabled)[[:space:]]*=/ { next }
        /^[[:space:]]*ServicesEnabled[[:space:]]*=/ {
            print "ServicesEnabled = dc"
            next
        }
        /^[[:space:]]*Kpt[A-Za-z]*[[:space:]]*=/ { next }
        /^[[:space:]]*NumberCyInstances[[:space:]]*=/ {
            print "NumberCyInstances = 0"
            next
        }
        /^[[:space:]]*Cy[0-9]+[A-Za-z]*[[:space:]]*=/ { next }
        section == "SSL" && /^[[:space:]]*NumberDcInstances[[:space:]]*=/ {
            print "NumberDcInstances = " ndc
            next
        }
        section == "SSL" && /^[[:space:]]*NumProcesses[[:space:]]*=/ {
            print "NumProcesses = " procs
            next
        }
        # The [SSL] instance blocks, comments included, are regenerated by emit_dc().
        section == "SSL" && (/^[[:space:]]*#/ || /^[[:space:]]*$/) { next }
        section == "SSL" && /^[[:space:]]*Dc[0-9]+[A-Za-z]*[[:space:]]*=/ { next }
        { print }
        iommu == 1 && /^[[:space:]]*\[GENERAL\][[:space:]]*$/ {
            print "SVMEnabled = 1"
            print "ATEnabled = 1"
        }
        END {
            if (section == "SSL")
                emit_dc()
        }
    ' "$CONF" >"$TMP"

    if cmp -s "$TMP" "$CONF"; then
        echo "  $CONF: already up to date"
        continue
    fi

    cp -a "$CONF" "$CONF.bak.$(date +%s)"
    cat "$TMP" >"$CONF"
    echo "  $CONF: updated"
done

#adf_ctl down
#modprobe -r qat_4xxx usdm_drv intel_qat
#sleep 1
#modprobe qat_4xxx
#sleep 1
#modprobe usdm_drv
#sleep 1
#adf_ctl up

adf_ctl restart

echo "Done. Run 'adf_ctl restart' (or 'systemctl restart qat') to apply."
